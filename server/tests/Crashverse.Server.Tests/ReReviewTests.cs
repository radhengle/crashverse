        DevGuard.CheckNotCloud(Env(new()));
    }

    [Theory]
    [InlineData("http://localhost:5000", true)] [InlineData("http://127.0.0.1:5000", true)] [InlineData("http://[::1]:5000", true)] [InlineData("https://127.0.0.5:1", true)]
    [InlineData("http://0.0.0.0:8080", false)] [InlineData("http://*:8080", false)] [InlineData("http://+:80", false)] [InlineData("http://[::]:80", false)] [InlineData("http://192.168.1.4:80", false)]
