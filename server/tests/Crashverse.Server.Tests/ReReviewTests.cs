    [Fact]
    public void N1_GoogleCloudProject_OnlyAllowedWithLocalEmulator()
    {
        Assert.Throws<ProdStartupException>(() => DevGuard.CheckNotCloud(Env(new() { ["GOOGLE_CLOUD_PROJECT"] = "p" })));
        Assert.Throws<ProdStartupException>(() => DevGuard.CheckNotCloud(Env(new() { ["GCLOUD_PROJECT"] = "p", ["FIRESTORE_EMULATOR_HOST"] = "10.1.2.3:8080" })));
        DevGuard.CheckNotCloud(Env(new() { ["GCLOUD_PROJECT"] = "demo-crashverse", ["FIRESTORE_EMULATOR_HOST"] = "127.0.0.1:8080" }));
