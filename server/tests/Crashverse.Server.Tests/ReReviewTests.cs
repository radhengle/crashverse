    [Fact]
    public async Task BE01_UnvalidatedBest_NeverOverwritesValidated_AndFailedReplayKeepsIt()
    {
        await using var h = await Harness.Start();
        var s = await h.Guest(); var key = s.pid + ":c1_l01";
        await h.Post("/v1/campaign/results", Harness.Win("c1_l01", await h.Attempt(s, "c1_l01"), 1, 4, 0.9f, 2), s);
        await new ReplayService(h.X).Enqueue((await h.X.Db.List<RunDoc>("runs")).Single().runId, "test");
        h.Replay.Fn = _ => new ReplayResult { won = true, shotsLeft = 1, destroyedRatio = 0.9f, bestCombo = 2 };
        await h.Job("/internal/jobs/replay");
        var validated = (await h.X.Db.Get<LevelBestDoc>("campaignBest", key)).best;
        Assert.True(validated > 0);
        Assert.Equal(validated, await new CampaignService(h.X).Total(s.pid));

        var r = await h.Post("/v1/campaign/results", Harness.Win("c1_l01", await h.Attempt(s, "c1_l01"), 2, 4, 1.0f, 9), s); // higher claim
        var rec = await h.X.Db.Get<LevelBestDoc>("campaignBest", key);
        Assert.Equal(validated, rec.best); Assert.True(rec.validated); Assert.True(rec.provisionalBest > validated);
        Assert.Equal(validated, r["levelBest"].GetInt32()); Assert.Equal(validated, r["total"].GetInt32());

        var second = (await h.X.Db.List<RunDoc>("runs")).Single(x => x.runId == rec.provisionalRunId).runId;
        await new ReplayService(h.X).Enqueue(second, "test");
        h.Replay.Fn = _ => new ReplayResult { won = false, shotsLeft = 0, destroyedRatio = 0.2f };
        await h.Job("/internal/jobs/replay");
        rec = await h.X.Db.Get<LevelBestDoc>("campaignBest", key);
        Assert.Equal(validated, rec.best); Assert.Equal(0, rec.provisionalBest); Assert.Null(rec.provisionalRunId);
        Assert.Equal(validated, await new CampaignService(h.X).Total(s.pid));
    }

