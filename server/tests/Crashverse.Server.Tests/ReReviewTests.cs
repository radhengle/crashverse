    // ---------------- N4 ----------------
    [Fact]
    public async Task N4_AgeToken_BoundToInstall_AndSingleUse()
    {
        await using var h = await Harness.Start();
        Assert.Equal("BAD_REQUEST", (await h.Post("/v1/agegate", new { birthYear = 1990, birthMonth = 1, country = "US" }, null)).Code);
        var tok = await h.AgeToken(device: "install-A");
        Assert.Equal("AGE_GATE_REQUIRED", (await h.Post("/v1/auth/guest", new { deviceInstallId = "install-B", ageToken = tok }, null)).Code);
        Assert.Equal(HttpStatusCode.OK, (await h.Post("/v1/auth/guest", new { deviceInstallId = "install-A", ageToken = tok }, null)).status);
        Assert.Equal("AGE_TOKEN_USED", (await h.Post("/v1/auth/guest", new { deviceInstallId = "install-A", ageToken = tok }, null)).Code);
        // a failed provider check does not burn the token
        var t2 = await h.AgeToken(device: "install-C");
        Assert.Equal("PROVIDER_TOKEN_INVALID", (await h.Post("/v1/auth/sign-in", new { provider = "facebook", token = "nope", deviceInstallId = "install-C", ageToken = t2 }, null)).Code);
        h.Facebook.Tokens["fb-n4"] = new ProviderIdentity { subject = "n4" };
        Assert.Equal(HttpStatusCode.OK, (await h.Post("/v1/auth/sign-in", new { provider = "facebook", token = "fb-n4", deviceInstallId = "install-C", ageToken = t2 }, null)).status);
    }

