        else Assert.Throws<ProdStartupException>(() => DevGuard.CheckLoopbackOnly(new[] { "http://localhost:1", url }));
    }

    // ---------------- N2 ----------------
    sealed class BrokenSecrets : ISecretProvider { public Task<byte[]> Get(string n) => throw new HttpRequestException("denied"); }

    [Fact]
    public void N2_ProdStartup_FailsWithoutPurchaseBindingSecret()
    {
        var none = Assert.Throws<ProdStartupException>(() => ServerApp.ProdContext(new ServerOptions { Env = CrashverseEnv.Prod }, new ServerApp.ProdAdapters()));
        Assert.Contains("secrets: not configured", none.Message); Assert.Contains("purchase-binding secret", none.Message);
        var broken = Assert.Throws<ProdStartupException>(() => ServerApp.ProdContext(new ServerOptions { Env = CrashverseEnv.Prod }, new ServerApp.ProdAdapters { Secrets = new BrokenSecrets() }));
        Assert.Contains("purchase-binding secret", broken.Message);
        var dev = Assert.Throws<ProdStartupException>(() => ServerApp.ProdContext(new ServerOptions { Env = CrashverseEnv.Prod }, new ServerApp.ProdAdapters { Secrets = new DevSecretProvider() }));
        Assert.Contains("secrets: dev-only implementation", dev.Message);
        Assert.Null(new ServerOptions().ObfuscationPepper); // never generated by default
    }

