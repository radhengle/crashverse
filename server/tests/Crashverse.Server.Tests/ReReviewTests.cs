    // ---------------- BE-03: ST-23/24/25/29/31 ----------------
    static async Task Debt(Harness h, Session s, int gems, int coins = 0)
    {
        var w = await new WalletService(h.X).Get(s.pid); w.gems = gems; w.coins = coins; await h.X.Db.Put("wallets", s.pid, w);
    }

    [Theory]
    [InlineData(500, 200, false)] // ST-23: debt 300, +500 → debt repaid first, balance 200, unlocked
    [InlineData(100, -200, true)] // ST-24: debt 300, +100 → still 200 in debt, locked
    [InlineData(300, 0, false)]   // ST-25: repaid to exactly 0 → unlocked at 0
    public async Task BE03_DebtRepayment(int income, int balance, bool locked)
    {
        await using var h = await Harness.Start();
        var s = await h.Guest(); await Debt(h, s, -300);
        await new EconomyService(h.X).GrantGems(s.pid, income, "test_income", "k");
        var w = await h.Wallet(s);
        Assert.Equal(balance, w.gems); Assert.Equal(locked, w.gemSpendLocked);
        var code = (await h.Post("/v1/season/premium/unlock", new { }, s)).Code;
        Assert.Equal(locked ? "GEM_DEBT_LOCKED" : "INSUFFICIENT_FUNDS", code);
    }

