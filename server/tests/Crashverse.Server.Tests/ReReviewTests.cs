    [Fact]
    public async Task BE03_ST31_RefundWhileOffline_ServerStateWinsOnNextSync()
    {
        await using var h = await Harness.Start();
        var s = await h.Guest();
        var t1 = h.PlayPurchase(s, "gems_small"); var t2 = h.PlayPurchase(s, "gems_small");
        await h.Verify(s, "gems_small", t1); await h.Verify(s, "gems_small", t2);
        await h.Post("/v1/store/buy", new { sku = "trail_confetti" }, s); // client last saw 80 gems, unlocked
        // client goes offline; refund lands server-side
        h.Play.Voided.Add(new PlayVoidedPurchase { purchaseToken = t1, voidedTimeMillis = h.X.NowMs });
        await h.Job("/internal/jobs/voided-poll");
        h.Advance(TimeSpan.FromDays(2)); await h.Renew(s); // reopen
        var w = await h.Wallet(s);
        Assert.Equal(-20, w.gems); Assert.True(w.gemSpendLocked);
        Assert.Equal("GEM_DEBT_LOCKED", (await h.Post("/v1/store/buy", new { sku = "emote_salute" }, s)).Code); // no local bypass
    }

    // ---------------- BE-04 ----------------
    [Fact]
    public async Task BE04_TieTimestamp_StableOnEqualReplaceResubmit()
    {
        await using var h = await Harness.Start();
        var lb = new Leaderboards(h.X); const string B = "campaign:c1_alltime";
        var a = await h.Guest(); var b = await h.Guest();
        await lb.Submit(B, a.pid, 1000, null, replace: true);
        h.Advance(TimeSpan.FromMinutes(5));
        await lb.Submit(B, b.pid, 1000, null, replace: true);
        var before = (await h.X.Db.List<BoardEntryDoc>("boards")).Single(e => e.playerId == a.pid).reachedUnixMs;
        h.Advance(TimeSpan.FromMinutes(5));
        await lb.Submit(B, a.pid, 1000, null, replace: true); // equal total again
        Assert.Equal(before, (await h.X.Db.List<BoardEntryDoc>("boards")).Single(e => e.playerId == a.pid).reachedUnixMs);
        Assert.Equal(a.pid, (await lb.Entries(B)).First().playerId); // earlier timestamp wins the tie
    }
